//! Issue #2130 — line-break hyphens must not become U+FFFD.
//!
//! Reproduces the downstream corruption seen on the Elsevier *Waste Management*
//! 2025 article (ScienceDirect S0956053X25001680), where a word broken across
//! a line (`pre-cipitation`, `sepa-ration`, `re-covery`, …) extracts as
//! `pre\u{FFFD} cipitation` because the line-break hyphen's code is missing
//! from the font's ToUnicode CMap.
//!
//! The committed fixture `tests/fixtures/issue_2130_linebreak_hyphen.pdf` is a
//! minimal, license-clean PDF: its only font is a `Type0` (composite) font
//! whose `ToUnicode` CMap covers every printable code **except** the single
//! code used for the line-break hyphen. Inline hyphens in the same font map
//! correctly, so the fixture also proves the inline-vs-line-break asymmetry.
//!
//! The fixture is generated by `gen_issue2130_fixture.py` (pure stdlib).
//!
//! On the current release this test FAILS (U+FFFD is emitted for the
//! line-break hyphen); once pdf_oxide maps the resolvable hyphen glyph to
//! U+002D / U+00AD it should pass.
use pdf_oxide::document::PdfDocument;

#[test]
fn line_break_hyphen_is_not_replacement_char() {
    let path = "tests/fixtures/issue_2130_linebreak_hyphen.pdf";
    let mut doc = PdfDocument::open(path).expect("open fixture");
    let chars = doc.extract_chars(0).expect("extract_chars");

    let mut fffd_count = 0usize;
    let mut text = String::new();
    for c in &chars {
        text.push(c.char);
        if c.char == '\u{FFFD}' {
            fffd_count += 1;
        }
    }

    println!("page-0 chars = {}, U+FFFD = {}", chars.len(), fffd_count);
    println!("text = {:?}", text);

    assert_eq!(
        fffd_count, 0,
        "extract_chars emitted {} U+FFFD chars on page 0; line-break hyphens \
         should map to U+002D / U+00AD, not the replacement character",
        fffd_count
    );
    assert!(
        text.contains("precipitation") && text.contains("lithium-ion"),
        "rejoined words missing; first 200 chars: {:?}",
        &text.chars().take(200).collect::<String>()
    );
}
